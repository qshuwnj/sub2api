import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import ts from 'typescript'

const input = process.argv[2]
if (!input) throw new Error('Pass the downloaded official MagicRings.jsx path')
const source = fs.readFileSync(input, 'utf8')
const ast = ts.createSourceFile(input, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.JSX)
const declaration = ast.statements
  .filter(ts.isVariableStatement)
  .flatMap(node => [...node.declarationList.declarations])
  .find(node => node.name.getText(ast) === 'MagicRings')
if (!declaration || !ts.isArrowFunction(declaration.initializer)) throw new Error('Missing component')
const component = declaration.initializer
const body = component.body.statements
const settings = body.filter(node => ts.isVariableStatement(node) &&
  node.declarationList.declarations.some(item => ['light', 'first', 'second', 'settings'].includes(item.name.getText(ast))))
const effect = body.filter(ts.isExpressionStatement).map(node => node.expression).find(node =>
  ts.isCallExpression(node) && node.expression.getText(ast) === 'useEffect' &&
  node.arguments[1]?.getText(ast) === '[generation]')
if (!effect) throw new Error('Missing renderer lifecycle')
const statements = [...effect.arguments[0].body.statements].slice(3)
const cleanup = statements.pop()
if (!ts.isReturnStatement(cleanup) || !ts.isArrowFunction(cleanup.expression)) throw new Error('Missing disposer')
const defaults = component.parameters[0].name.elements
  .filter(node => !['className', 'style'].includes(node.name.getText(ast)))
  .map(node => node.getText(ast)).join(',\n')
const helpers = ast.statements.filter(node => node.end < declaration.pos &&
  !ts.isImportDeclaration(node) && !ts.isExpressionStatement(node) &&
  !node.getText(ast).includes('const MagicRings ='))
// Extract the original shaders and render loop; replace only React lifecycle bindings.
let rendering = statements.map(node => node.getText(ast)).join('\n')
rendering = rendering
  .replace(' && generation === 0', '')
  .replace('const onRestored = () => setGeneration(value => value + 1);', '')
  .replace("canvas.addEventListener('webglcontextrestored', onRestored);", '')
  .replace("if (!programFor('glow', []) || !programFor('compose', []) || !programFor('line', [])) return;",
    "if (!programFor('glow', []) || !programFor('compose', []) || !programFor('line', [])) {\n" +
    "programs.forEach(entry => entry && gl.deleteProgram(entry.program));\nreturn null;\n}")
  .replace('const onPointerDown = event => {',
    "const onPointerDown = event => {\n" +
    "if (event.target instanceof Element && event.target.closest('form, button, a, input')) return;")
let disposal = cleanup.expression.getText(ast)
disposal = disposal.replace("canvas.removeEventListener('webglcontextrestored', onRestored);", '')
if (/useEffect|useRef|setGeneration|onRestored/.test(rendering + disposal)) throw new Error('Unconverted React binding')
const hash = crypto.createHash('sha256').update(source).digest('hex')
const output = [
  '/*! Magic Rings by David Hazan / React Bits. See LICENSE.react-bits.md.',
  ' * Source: https://github.com/DavidHDev/react-bits/blob/main/src/content/Backgrounds/MagicRings/MagicRings.jsx',
  ` * Upstream SHA256: ${hash}`,
  ' * Generated by tools/vendor-magic-rings.mjs; original shaders and ring motion preserved. */',
  ...helpers.map(node => node.getText(ast)),
  'export function createMagicRings(container, canvas, options = {}) {',
  `const { ${defaults} } = options;`,
  ...settings.map(node => node.getText(ast)),
  'const settingsRef = { current: settings };',
  'const wakeRef = { current: null };',
  rendering,
  `return { dispose: ${disposal} };`,
  '}',
  '',
].join('\n').replace(/[ \t]+$/gm, '')
const folder = path.resolve('src/components/auth/magic-rings')
fs.mkdirSync(folder, { recursive: true })
fs.writeFileSync(path.join(folder, 'renderer.js'), output)
fs.copyFileSync('src/components/home/ghost-fibers/LICENSE.react-bits.md', path.join(folder, 'LICENSE.react-bits.md'))
console.log(`Vendored original Magic Rings renderer: ${hash}`)
